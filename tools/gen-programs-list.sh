#!/bin/sh
# Generate the one header the program registry includes.
#
# Every ring-3 program's image is a generated header holding a `static const` array, and a
# `static const` array in a header is only usable from the translation unit that includes
# it.  So the registry includes each of them itself, and this script exists only to write
# the list of them -- which is the thing that would otherwise have to be edited by hand
# every time a program is added, and would then be wrong.
#
# The names are emitted in the registry's own order so that a program's index is stable.
set -e

inc_dir=$1
out=$2
shift 2

tmp="$out.tmp"

{
    echo "/* Generated by tools/gen-programs-list.sh -- do not edit."
    echo " * The ring-3 programs this kernel can start, one include each."
    echo " */"
    echo "#ifndef MINX_PROGRAMS_LIST_H"
    echo "#define MINX_PROGRAMS_LIST_H"
    echo
    for p in "$@"; do
        echo "#include \"${p}_image.h\""
    done
    echo
    echo "/* The registry's table, generated here rather than written by hand in"
    echo " * kernel/lib/programs.c."
    echo " *"
    echo " * A program's name is the directory it lives in, which is also its file name, so"
    echo " * there is exactly one place a program is named -- and the one thing that has to be"
    echo " * true of the table is that it mentions every program that exists.  Hand-written, it"
    echo " * is a list that can be out of date, and the symptom is a program that the Makefile"
    echo " * built, put in the initrd and nothing can start."
    echo " *"
    # Single-quoted because of the backticks.  Inside double quotes a backtick starts a
    # command substitution, so this line was running `stack_pages` as a command -- printing
    # "stack_pages: command not found" to stderr and writing a comment into the generated
    # header with a hole in the middle of the sentence.  It was never fatal, which is why
    # it survived: the header still compiled, and the only symptom was noise on stderr and
    # a generated comment that did not say what it meant.
    echo ' * `stack_pages` is a property of the program rather than of whoever starts it: a'
    echo " * program whose stack is too small for its own recursion should fail the same way"
    echo " * whoever runs it.  8 pages (32 KiB) is enough for every program here and small"
    echo " * enough that a stress test forking in the hundreds is bounded by something. */"
    echo "#define MINX_PROGRAM_TABLE \\"
    first=1
    for p in "$@"; do
        echo "    { \"$p\", ${p}_image, ${p}_image_len, 8, \"$p\" }, \\"
    done
    echo
    echo "#endif /* MINX_PROGRAMS_LIST_H */"
} > "$tmp"

mv "$tmp" "$out"