#!/usr/bin/env python3
"""minx - turn a binary into a C array.

Some things have to be inside the kernel image rather than beside it, and a user program
is the first of them.  The loader needs a program to load, and there is no filesystem
until phase 8, so the image goes into the kernel as an array.

Written as a tool rather than as an `xxd -i` in the Makefile for two reasons: `xxd -i`
emits its own declaration and its own array name, so the header it produces cannot be
included twice and its name cannot be chosen by whoever includes it; and the output
needs a length and a description, because a megabyte of numbers with nothing saying what
they are is worse than no image at all.
"""
import sys


def main() -> int:
    if len(sys.argv) != 5:
        sys.stderr.write("usage: bin2c.py <input> <output.h> <symbol> <description>\n")
        return 2

    src, dst, symbol, desc = sys.argv[1:5]

    with open(src, "rb") as f:
        data = f.read()

    if not data:
        sys.stderr.write(f"bin2c: {src} is empty\n")
        return 1

    with open(dst, "w") as f:
        f.write("/* Generated by tools/bin2c.py -- do not edit.\n")
        f.write(f" * {desc}\n")
        f.write(f" * Source: {src} ({len(data)} bytes)\n */\n")
        f.write("#ifndef MINX_GENERATED_IMAGE_H\n")
        f.write("#define MINX_GENERATED_IMAGE_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"static const uint64_t {symbol}_len = {len(data)};\n")
        f.write(f"static const unsigned char {symbol}[] = {{\n")

        for i in range(0, len(data), 12):
            row = ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
            f.write(f"    {row},\n")

        f.write("};\n\n")
        f.write("#endif /* MINX_GENERATED_IMAGE_H */\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())
