#!/bin/sh
# Generate the user side's syscall numbers from the kernel's.
#
# There is exactly one place a syscall number is written down -- the enum in
# kernel/include/syscall.h -- and this exists so that the *user* side reads it rather than
# copying it.  The copy is what breaks: renumbering the enum updated user/common/minx_user.h
# and not the `movl $4, %eax` in user/common/start.S, so every program's exit syscall became
# `lseek`.  A program printed its last line, returned from main, and spun in the entry
# stub's "exit does not return either" loop for ever -- passing every check it had printed
# and never exiting at all.
#
# Two outputs from one parse, because the two consumers are different languages:
#
#   <out.h>   `#define SYS_READ 0`          -- for user/common/minx_user.h
#   <out.inc> `SYS_READ = 0`                -- for user/common/start.S, which is
#                                              assembly and cannot see a C header
#
# The `.inc` is the reason this is worth a generator rather than a header: an assembly file
# including a C header gets macros and nothing else, so the numbers have to be emitted a
# second time in a form the assembler accepts.  Both come from the same pass over the same
# text, so they cannot disagree with each other.
#
# The parser is a line filter rather than a real C parser on purpose.  It only has to
# understand this one enum, and a build that breaks loudly when the enum is written in an
# unfamiliar way is a better build than one that silently stops finding the numbers.
set -e

in=$1
out_h=$2
out_inc=$3

# `SYS_NAME = number,` inside the enum, with any amount of space around the `=`.
names=$(sed -n 's/^[[:space:]]*\(SYS_[A-Z0-9_]*\)[[:space:]]*=[[:space:]]*\([0-9][0-9]*\)[[:space:]]*,.*/\1/p' "$in")
count=$(printf '%s\n' "$names" | grep -c .)

if [ -z "$names" ]; then
    echo "gen-syscall-table: found no syscall numbers in $in" >&2
    echo "gen-syscall-table: the enum has been written in a way this does not read" >&2
    exit 1
fi

tmp_h="$out_h.tmp"
tmp_inc="$out_inc.tmp"

{
    echo "/* Generated by tools/gen-syscall-table.sh -- do not edit."
    echo " * The kernel's syscall numbers, read out of kernel/include/syscall.h."
    echo " *"
    echo " * This is the user side of one enum.  It used to be a second, hand-written copy of"
    echo " * it, and a hand-written copy is a copy that is wrong the next time the numbers"
    echo " * move -- which is exactly what happened when the enum was renumbered and"
    echo " * user/common/start.S kept the old number for exit()."
    echo " */"
    echo "#ifndef MINX_SYSCALL_TABLE_H"
    echo "#define MINX_SYSCALL_TABLE_H"
    echo
    printf '%s\n' "$names" | while read -r n; do
        v=$(sed -n "s/^[[:space:]]*$n[[:space:]]*=[[:space:]]*\([0-9][0-9]*\)[[:space:]]*,.*/\1/p" "$in")
        echo "#define $n $v"
    done
    echo
    echo "#endif /* MINX_SYSCALL_TABLE_H */"
} > "$tmp_h"

{
    echo "/* Generated by tools/gen-syscall-table.sh -- do not edit."
    echo " * The same numbers as minx_syscall_table.h, in the form the assembler accepts."
    echo " *"
    echo " * An assembly file cannot see a C header's macros, so the entry stub's exit"
    echo " * syscall would otherwise be a literal -- and a literal in a second language is a"
    echo " * second thing to forget to update."
    echo " */"
    printf '%s\n' "$names" | while read -r n; do
        v=$(sed -n "s/^[[:space:]]*$n[[:space:]]*=[[:space:]]*\([0-9][0-9]*\)[[:space:]]*,.*/\1/p" "$in")
        echo "$n = $v"
    done
} > "$tmp_inc"

mv "$tmp_h" "$out_h"
mv "$tmp_inc" "$out_inc"

echo "gen-syscall-table: $count syscall numbers -> $out_h, $out_inc"